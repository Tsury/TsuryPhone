"""PlatformIO pre-build script: build-time secrets and firmware identity.

Secrets come only from the environment and become compiler defines. The build stops
when a secret the firmware uses is missing. Never print their values.
Version, source commit and build time go to src/generated/buildInfo.h.
"""

import datetime
import os
from pathlib import Path
import re
import subprocess
import sys

Import("env")  # noqa: F821  (provided by PlatformIO/SCons)

# Each secret the firmware uses, with the pattern its value must match.
# SMS forwarding (#7) adds TSURYPHONE_SMS_WEBHOOK_ID and TSURYPHONE_SMS_ACK_KEY here.
SECRETS = {
    "TSURYPHONE_OTA_PASSWORD_SHA256": re.compile(r"[0-9a-f]{64}"),
}

ROOT = Path(env.subst("$PROJECT_DIR"))  # noqa: F821


def fail(message):
    print(f"error: {message}", file=sys.stderr)
    env.Exit(1)  # noqa: F821


def git(*args):
    try:
        return subprocess.check_output(
            ["git", *args], cwd=ROOT, text=True, stderr=subprocess.DEVNULL
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        return ""


def c_string(value):
    return '\\"' + value + '\\"'


missing = [name for name in SECRETS if not os.environ.get(name)]
if missing:
    fail(
        "missing build secrets in the environment: "
        + ", ".join(missing)
        + " (live builds: vault values; bench builds: synthetic values)"
    )
for name, pattern in SECRETS.items():
    value = os.environ[name].strip().lower()
    if not pattern.fullmatch(value):
        fail(f"{name} has the wrong format")
    env.Append(CPPDEFINES=[(name, c_string(value))])  # noqa: F821

commit = git("rev-parse", "HEAD") or "unknown"
if git("status", "--porcelain", "--untracked-files=no"):
    commit += "-dirty"
version = os.environ.get("TSURYPHONE_FW_VERSION") or git(
    "describe", "--tags", "--always", "--dirty"
)
if version and not re.fullmatch(r"[A-Za-z0-9._+-]{1,40}", version):
    fail("TSURYPHONE_FW_VERSION may hold only letters, digits and . _ + - (at most 40)")
build_time = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

header = ROOT / "src" / "generated" / "buildInfo.h"
header.parent.mkdir(parents=True, exist_ok=True)
header.write_text(
    "#pragma once\n"
    "// Generated by scripts/build_flags.py for each build.\n"
    f'#define TSURYPHONE_FW_VERSION "{version or "unknown"}"\n'
    f'#define TSURYPHONE_FW_COMMIT "{commit}"\n'
    f'#define TSURYPHONE_FW_BUILD_TIME "{build_time}"\n',
    encoding="utf-8",
)
